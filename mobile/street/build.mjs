// Builds 5IVE STREET (the 3D 3v3 game) into one self-contained HTML page:
//   street/dist/index.html           — open in a browser for development
//   src/street/html.generated.ts     — the same page as a string, loaded by the app's WebView
//   ../public/street/index.html      — the same page on the website, at /street
//
//   node street/build.mjs            one-off production build
//   node street/build.mjs --watch    rebuild on change (dev, unminified) and serve dist/ on :5180
import * as esbuild from "esbuild";
import { createReadStream, mkdirSync, readFileSync, statSync, symlinkSync, writeFileSync, existsSync } from "node:fs";
import { createServer } from "node:http";
import { dirname, extname, join, normalize } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const watch = process.argv.includes("--watch");
const distDir = join(here, "dist");
const generated = join(here, "../src/street/html.generated.ts");
// The website serves the same page at /street (rewrite in next.config.ts).
const website = join(here, "../../public/street/index.html");

function writeOutputs(js) {
  const template = readFileSync(join(here, "index.html"), "utf8");
  const safe = js.replace(/<\/script/gi, "<\\/script");
  const html = template.replace("<!--GAME-->", () => `<script>${safe}</script>`);
  mkdirSync(distDir, { recursive: true });
  writeFileSync(join(distDir, "index.html"), html);
  // Card art for local testing: dist/cards → the website's public/cards.
  const cards = join(distDir, "cards");
  if (!existsSync(cards)) symlinkSync(join(here, "../../public/cards"), cards);
  if (!watch) {
    mkdirSync(dirname(website), { recursive: true });
    writeFileSync(website, html);
    mkdirSync(dirname(generated), { recursive: true });
    writeFileSync(
      generated,
      "// Generated by `npm run build:street` from mobile/street — do not edit.\n" +
        `export const STREET_HTML = ${JSON.stringify(html)};\n`,
    );
  }
  const kb = (Buffer.byteLength(html) / 1024).toFixed(0);
  console.log(`[street] built ${kb} KB${watch ? " (dev)" : ""}`);
}

const options = {
  entryPoints: [join(here, "src/main.ts")],
  bundle: true,
  format: "iife",
  target: ["safari16"],
  minify: !watch,
  sourcemap: watch ? "inline" : false,
  write: false,
  legalComments: "none",
  logLevel: "warning",
};

if (watch) {
  const ctx = await esbuild.context({
    ...options,
    plugins: [{
      name: "write-html",
      setup(build) {
        build.onEnd((result) => {
          if (result.errors.length) return;
          writeOutputs(result.outputFiles[0].text);
        });
      },
    }],
  });
  await ctx.watch();
  const types = { ".html": "text/html", ".jpg": "image/jpeg", ".png": "image/png", ".js": "text/javascript" };
  const port = Number(process.env.PORT ?? 5180);
  createServer((req, res) => {
    const path = normalize(decodeURIComponent(new URL(req.url, "http://x").pathname)).replace(/^(\.\.[/\\])+/, "");
    let file = join(distDir, path);
    try { if (statSync(file).isDirectory()) file = join(file, "index.html"); } catch {}
    if (!existsSync(file)) { res.writeHead(404); res.end(); return; }
    res.writeHead(200, { "content-type": types[extname(file)] ?? "application/octet-stream", "cache-control": "no-store" });
    createReadStream(file).pipe(res);
  }).listen(port, () => console.log(`[street] http://localhost:${port}`));
} else {
  const result = await esbuild.build(options);
  writeOutputs(result.outputFiles[0].text);
}
